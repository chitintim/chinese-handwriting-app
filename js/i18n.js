(function () {
  'use strict';
  // Interface language (docs/SPEC.md revision 22): 繁 (the source strings), 简 (build-generated from them by OpenCC, js/i18n-simp.js) and EN (hand-written, js/i18n-en.js).
  // This is about the CONTROLS only: library texts, the characters, 解說 and 落款 stay Chinese in every mode. The writing text's own 繁體 / 简体 (settings.cfg.script, libScript) is a separate choice.
  //   MX.t('開始')                              the string for the current language; the 繁 source string is the key
  //   MX.t('已完成 {n} 份', { n: 3 })           {slots} are filled in after the lookup (a sentence is translated whole, never glued together)
  //   EN value = ['{n} file', '{n} files']      one / other by vars.n
  var MX = window.MX = window.MX || {};
  var LANGS = ['trad', 'simp', 'en'], HTML_LANG = { trad: 'zh-Hant', simp: 'zh-Hans', en: 'en' };
  var EN = {}, ENV = {}, SIMP = {}, lang = 'trad', listeners = [], missing = [];
  var LS_KEY = 'mx:uiLang';       // a mirror of settings.uiLang for the screens that are drawn before the settings are loaded (an error at start)

  function lsGet() { try { return window.localStorage.getItem(LS_KEY); } catch (e) { return null; } }
  function lsSet(v) { try { window.localStorage.setItem(LS_KEY, v); } catch (e) { /* ignore */ } }
  function valid(v) { return LANGS.indexOf(v) >= 0 ? v : null; }

  // navigator.language -> the first-run default: English -> EN; clearly Simplified (zh-CN / zh-SG / zh-Hans...) -> 简; everything else (zh-TW / zh-HK / zh-Hant / unknown) -> 繁
  function detect(nav) {
    var tags = [], l;
    try { tags = nav && nav.languages && nav.languages.length ? Array.prototype.slice.call(nav.languages) : [nav && nav.language]; } catch (e) { tags = []; }
    l = String(tags[0] || '').toLowerCase().replace(/_/g, '-');
    if (/^zh(-|$)/.test(l)) return /-(hans|cn|sg|my)(-|$)/.test(l) ? 'simp' : 'trad';
    if (/^en(-|$)/.test(l)) return 'en';
    return 'trad';
  }

  var I = MX.I18n = {
    LANGS: LANGS,
    SHORT: { trad: '繁', simp: '简', en: 'EN' },
    detect: detect,
    get lang() { return lang; },
    missing: missing,
    addEn: function (t) {
      EN = t; I.EN = t; ENV = {};
      Object.keys(t).forEach(function (k) { [].concat(t[k]).forEach(function (v) { ENV[v] = 1; }); });       // an English value that is looked up again (a label passed through two sinks) is not a miss
    },
    addSimp: function (t) { SIMP = t; I.SIMP = t; },
    EN: EN, SIMP: SIMP,
    isEn: function () { return lang === 'en'; },
    // the language a device starts with: the test override, else the mirror of the last choice, else the browser language
    initial: function () {
      return valid(window.__MX_UILANG) || valid(lsGet()) || detect(navigator);
    },
    // Called by Model.init with the stored value (undefined = nothing stored: a new device detects, a device that already has data stays 繁 as before)
    start: function (stored, hadSettings) {
      var v = valid(stored) || (hadSettings ? (valid(window.__MX_UILANG) || 'trad') : I.initial());
      I.apply(v);
      return v;
    },
    apply: function (v) {
      lang = valid(v) || 'trad';
      try { document.documentElement.setAttribute('lang', HTML_LANG[lang]); document.documentElement.setAttribute('data-ui', lang); } catch (e) { /* ignore */ }
      lsSet(lang);
      try { if (window.MoBridge && window.MoBridge.setLang) window.MoBridge.setLang(lang); } catch (e) { /* ignore */ }
      try { document.title = I.title(); } catch (e) { /* ignore */ }
    },
    // the page for the install steps in the interface language (script-free pages generated by scripts/i18n.py)
    downloadHref: function () { return lang === 'en' ? 'download/en.html' : (lang === 'simp' ? 'download/zh-hans.html' : 'download/'); },
    title: function () { return lang === 'en' ? '墨字帖 Moxie' : '墨字帖'; },
    // switch the interface language: saved device-level, then every listener (main.js draws the current screen again)
    set: function (v) {
      v = valid(v);
      if (!v || v === lang) return;
      I.apply(v);
      try {
        if (MX.Model && MX.Model.settings) { MX.Model.settings.uiLang = v; MX.Model.saveSettings(); }
      } catch (e) { if (MX.err) MX.err(e); }
      listeners.slice().forEach(function (f) { try { f(v); } catch (e) { if (MX.err) MX.err(e); } });
    },
    onChange: function (f) { listeners.push(f); },
    // a name for each language, written in that language (the toggle itself is never translated)
    name: function (v) { return { trad: '繁體中文', simp: '简体中文', en: 'English' }[v]; },
    // in EN, words that name a stretch of Chinese (not a sentence) go before it with a space ("描 Trace"): join list items like "1 h 30 min"
    sep: function () { return lang === 'en' ? ' ' : ''; },
    // the key in every language (繁, 简, EN): for code that must recognise a message whatever language it was made in
    all: function (key) { return [key, SIMP[key] !== undefined ? SIMP[key] : key, Array.isArray(EN[key]) ? EN[key][1] : (EN[key] !== undefined ? EN[key] : key)]; },
    // an object whose string properties are translated whenever they are read (module-level tables of sentences: STR = {...})
    live: function (obj, skip) {
      Object.keys(obj).forEach(function (k) {
        var raw = obj[k];
        if (typeof raw !== 'string' || (skip && skip.indexOf(k) >= 0)) return;
        Object.defineProperty(obj, k, { get: function () { return MX.t(raw); }, enumerable: true, configurable: true });
      });
      return obj;
    }
  };

  var has = Object.prototype.hasOwnProperty;
  function count(v) { return v ? (v.n !== undefined ? +v.n : +v.d) : NaN; }       // the number that picks one / other
  function fill(s, v) {
    return v ? String(s).replace(/\{(\w+)\}/g, function (m, k) { return v[k] !== undefined ? String(v[k]) : m; }) : s;
  }
  MX.t = function (key, vars) {
    var s = key, e;
    if (lang === 'en') {
      e = has.call(EN, key) ? EN[key] : undefined;
      if (e === undefined) {
        if (/[\u3400-\u9fff]/.test(key) && !ENV[key] && missing.indexOf(key) < 0) missing.push(key);
      } else {
        s = Array.isArray(e) ? e[count(vars) === 1 ? 0 : 1] : e;
      }
    } else if (lang === 'simp') {
      if (has.call(SIMP, key)) s = SIMP[key];
    }
    return fill(s, vars);
  };
  // the translated key without filling slots
  MX.t.raw = function (key) { return MX.t(key); };
  I.apply(I.initial());
})();
